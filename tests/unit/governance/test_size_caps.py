class TestFileCap:
    """The hard cap: 500 lines, or a listed file's own recorded ceiling."""

    def test_no_file_exceeds_its_ceiling(self):
        offenders = []
        for path in _iter_src_files():
            rel = str(path.relative_to(REPO_ROOT))
            ceiling = FILE_ALLOWLIST.get(rel, FILE_CAP)
            size = measure_module(path).file_lines
            if size > ceiling:
                offenders.append((rel, size, ceiling))

        assert offenders == [], f"file(s) over their cap/ceiling: {offenders}"

    def test_the_allowlist_has_exactly_three_entries(self):
        """Not a magic number: the spec's own measured facts named exactly
        these three files as the honest raw-line overages that survive the
        executable-statement metric. A fourth would need its own disclosure.
        """
        assert len(FILE_ALLOWLIST) == 3

    def test_no_allowlisted_file_has_dropped_to_or_under_the_cap(self):
        """A listed file back under FILE_CAP is stale — the allowlist is a
        live ceiling, not a historical record.
        """
        stale = []
        for rel in FILE_ALLOWLIST:
            size = measure_module(REPO_ROOT / rel).file_lines
            if size <= FILE_CAP:
                stale.append((rel, size))

        assert stale == [], f"allowlist entries at/under the cap — remove them: {stale}"


def _locate_baseline_subject(key: str) -> tuple[int | None, str | None]:
    """Returns (current_size, kind) for a ``path::qualname`` baseline key, or
    ``(None, None)`` if the file or the qualname inside it no longer exists.
    """
    rel, _, name = key.partition("::")
    path = REPO_ROOT / rel
    if not path.exists():
        return None, None
    measurement = measure_module(path)
    if name in measurement.classes:
        return measurement.classes[name], "class"
    if name in measurement.functions:
        return measurement.functions[name], "function"
    return None, None


class TestSizeCapRatchet:
    """The ratchet: a class/function may not exceed its cap unless it is in
    ``SIZE_BASELINE``, and a baseline entry may not exceed its own recorded
    ceiling either — so the allowlist can only shrink, never grow silently.
    """

    def test_every_overage_is_baselined_or_under_its_cap(self):
        problems = []
        for path in _iter_src_files():
            rel = str(path.relative_to(REPO_ROOT))
            measurement = measure_module(path)
            for cap, items in (
                (CLASS_CAP, measurement.classes),
                (FUNCTION_CAP, measurement.functions),
            ):
                for name, size in items.items():
                    key = f"{rel}::{name}"
                    ceiling = SIZE_BASELINE.get(key, cap)
                    if size > ceiling:
                        problems.append((key, size, ceiling))

        assert problems == [], (
            f"class/function(es) over their cap or recorded ceiling — add a baseline entry "
            f"with a one-line reason, or shrink: {problems}"
        )

    def test_no_baseline_entry_has_dropped_to_or_under_its_cap(self):
        stale = []
        for key in SIZE_BASELINE:
            size, kind = _locate_baseline_subject(key)
            if size is None:
                stale.append((key, "renamed or deleted"))
                continue
            cap = CLASS_CAP if kind == "class" else FUNCTION_CAP
            if size <= cap:
                stale.append((key, size))

        assert stale == [], f"baseline entries renamed/deleted or at/under cap: {stale}"

    def test_baseline_entries_do_not_exceed_their_own_recorded_ceiling(self):
        """An entry is a *ceiling*, not licence to grow further unnoticed."""
        grown = []
        for key, ceiling in SIZE_BASELINE.items():
            size, _ = _locate_baseline_subject(key)
            if size is not None and size > ceiling:
                grown.append((key, size, ceiling))

        assert grown == [], f"baseline entries grew past their recorded ceiling: {grown}"

    def test_regenerating_the_baseline_reproduces_it_exactly(self):
        """The mechanical regeneration step this file's docstring describes,
        run as a test: if the tree has not changed, ``--print-baseline``'s
        output must equal ``SIZE_BASELINE`` exactly — proving the entry point
        and the embedded dict have not drifted apart.
        """
        regenerated: dict[str, int] = {}
        for path in _iter_src_files():
            rel = str(path.relative_to(REPO_ROOT))
            measurement = measure_module(path)
            for name, size in measurement.classes.items():
                if size > CLASS_CAP:
                    regenerated[f"{rel}::{name}"] = size
            for name, size in measurement.functions.items():
                if size > FUNCTION_CAP:
                    regenerated[f"{rel}::{name}"] = size

        assert regenerated == SIZE_BASELINE


