_COMPOUND_TYPES: tuple[type, ...] = (
    ast.If,
    ast.For,
    ast.AsyncFor,
    ast.While,
    ast.With,
    ast.AsyncWith,
    ast.Try,
    ast.TryStar,
    ast.Match,
)
_DEF_TYPES: tuple[type, ...] = (ast.FunctionDef, ast.AsyncFunctionDef)


def _is_docstring(stmt: ast.stmt, index: int) -> bool:
    return (
        index == 0
        and isinstance(stmt, ast.Expr)
        and isinstance(stmt.value, ast.Constant)
        and isinstance(stmt.value.value, str)
    )


def _sub_bodies(stmt: ast.stmt) -> list[list[ast.stmt]]:
    """Every nested statement list a non-def/class compound statement owns."""
    if isinstance(stmt, ast.If):
        return [stmt.body, stmt.orelse]
    if isinstance(stmt, (ast.For, ast.AsyncFor, ast.While)):
        return [stmt.body, stmt.orelse]
    if isinstance(stmt, (ast.With, ast.AsyncWith)):
        return [stmt.body]
    if isinstance(stmt, (ast.Try, ast.TryStar)):
        bodies = [stmt.body, stmt.orelse, stmt.finalbody]
        bodies.extend(handler.body for handler in stmt.handlers)
        return bodies
    if isinstance(stmt, ast.Match):
        return [case.body for case in stmt.cases]
    return []


def _fold_lines(stmts: list[ast.stmt]) -> set[int]:
    """Executable-statement lines for a body, folding nested defs/classes
    directly in rather than keying them separately (ruling 3). Used for a
    function's own body, and for any compound statement's children.
    """
    lines: set[int] = set()
    for index, stmt in enumerate(stmts):
        if _is_docstring(stmt, index):
            continue
        if isinstance(stmt, (*_DEF_TYPES, ast.ClassDef)):
            lines.add(stmt.lineno)
            lines |= _fold_lines(stmt.body)
            continue
        if isinstance(stmt, _COMPOUND_TYPES):
            lines.add(stmt.lineno)
            for sub in _sub_bodies(stmt):
                lines |= _fold_lines(sub)
            continue
        end = stmt.end_lineno or stmt.lineno
        lines.update(range(stmt.lineno, end + 1))
    return lines


def _measure_class_body(
    stmts: list[ast.stmt], qualname_prefix: str, functions_out: dict[str, int]
) -> int:
    """A class's own total size: its directly-owned lines plus every
    method's own size, each method recorded under ``Class.method``. A class
    nested inside a class folds into the outer one with no key of its own —
    the repo has no such shape today, and the caps are about statement
    volume, not nesting depth.
    """
    own_lines: set[int] = set()
    methods_total = 0
    for index, stmt in enumerate(stmts):
        if _is_docstring(stmt, index):
            continue
        if isinstance(stmt, _DEF_TYPES):
            # The method's own header line counts toward *its* total (below),
            # not the class's `own_lines` — added once, via `methods_total`.
            qualname = f"{qualname_prefix}.{stmt.name}"
            size = 1 + len(_fold_lines(stmt.body))
            functions_out[qualname] = size
            methods_total += size
            continue
        if isinstance(stmt, ast.ClassDef):
            methods_total += 1 + _measure_class_body(
                stmt.body, f"{qualname_prefix}.{stmt.name}", functions_out
            )
            continue
        if isinstance(stmt, _COMPOUND_TYPES):
            own_lines.add(stmt.lineno)
            for sub in _sub_bodies(stmt):
                own_lines |= _fold_lines(sub)
            continue
        end = stmt.end_lineno or stmt.lineno
        own_lines.update(range(stmt.lineno, end + 1))
    return len(own_lines) + methods_total


@dataclass
class Measurement:
    file_lines: int
    classes: dict[str, int] = field(default_factory=dict)
    functions: dict[str, int] = field(default_factory=dict)


def measure_module(path: Path) -> Measurement:
    """Measure one module's executable-statement size, per file/class/function."""
    source = path.read_text(encoding="utf-8")
    tree = ast.parse(source)

    classes: dict[str, int] = {}
    functions: dict[str, int] = {}
    file_lines: set[int] = set()

    for index, stmt in enumerate(tree.body):
        if _is_docstring(stmt, index):
            continue
        if isinstance(stmt, ast.ClassDef):
            # The class's own header line counts toward its own total (below),
            # rolled into `total_file` via `sum(classes.values())` — not added
            # to `file_lines` directly, which would double it.
            classes[stmt.name] = 1 + _measure_class_body(stmt.body, stmt.name, functions)
            continue
        if isinstance(stmt, _DEF_TYPES):
            functions[stmt.name] = 1 + len(_fold_lines(stmt.body))
            continue
        if isinstance(stmt, _COMPOUND_TYPES):
            file_lines.add(stmt.lineno)
            for sub in _sub_bodies(stmt):
                file_lines |= _fold_lines(sub)
            continue
        end = stmt.end_lineno or stmt.lineno
        file_lines.update(range(stmt.lineno, end + 1))

    top_level_functions = sum(size for name, size in functions.items() if "." not in name)
    total_file = len(file_lines) + sum(classes.values()) + top_level_functions
    return Measurement(file_lines=total_file, classes=classes, functions=functions)


def _iter_src_files(src_root: Path = SRC_ROOT) -> list[Path]:
    """Every ``.py`` under ``src_root`` except the ``custom/`` strategies
    submodule — an unversioned git submodule this repo cannot pin (the
    ``STRATEGY_MODULES`` precedent in ``test_live_stop_path_is_inert.py``).
    Walking into it made the verdict depend on whether the submodule was
    checked out: a fresh worktree saw its baseline entries as deleted.
    """
    submodule = src_root / "core" / "strategies" / "custom"
    return sorted(path for path in src_root.rglob("*.py") if not path.is_relative_to(submodule))


def _print_baseline() -> None:
    """Entry point: ``python -m tests.unit.governance.test_size_caps --print-baseline``.

    Prints every current class/function overage in the ``SIZE_BASELINE``
    literal form this file embeds, so regenerating after a deliberate split
    is mechanical rather than hand-counted.
    """
    entries: list[tuple[str, int]] = []
    for path in _iter_src_files():
        rel = str(path.relative_to(REPO_ROOT))
        measurement = measure_module(path)
        for class_name, size in measurement.classes.items():
            if size > CLASS_CAP:
                entries.append((f"{rel}::{class_name}", size))
        for func_name, size in measurement.functions.items():
            if size > FUNCTION_CAP:
                entries.append((f"{rel}::{func_name}", size))

    entries.sort()
    print(f"SIZE_BASELINE: dict[str, int] = {{  # {len(entries)} entries")
    for key, size in entries:
        print(f'    "{key}": {size},')
    print("}")


class TestMeasureModuleMetric:
    """Pins the metric itself against synthetic sources — one fixture per
    metric ruling, plus the basics, so nobody has to reverse-engineer the
    metric from the baseline numbers alone.
    """

    def test_a_docstring_only_module_measures_zero(self, tmp_path):
        source = '"""\n' + ("line of prose\n" * 600) + '"""\n'
        path = tmp_path / "docstring_only.py"
        path.write_text(source)

        assert measure_module(path).file_lines == 0

    def test_a_compound_statement_counts_once(self, tmp_path):
        source = "def f():\n    if True:\n        x = 1\n        y = 2\n"
        path = tmp_path / "compound.py"
        path.write_text(source)

        # own header (1) + if header (1) + x=1 (1) + y=2 (1)
        assert measure_module(path).functions["f"] == 4

    def test_a_non_docstring_multiline_string_in_statement_position_counts_every_line(
        self, tmp_path
    ):
        source = (
            'def f():\n    query = (\n        "line1"\n        "line2"\n        "line3"\n    )\n'
        )
        path = tmp_path / "multiline.py"
        path.write_text(source)

        tree = ast.parse(source)
        assign = tree.body[0].body[0]
        span = (assign.end_lineno or assign.lineno) - assign.lineno + 1

        # own header (1) + every line the multi-line assign spans — not the
        # 1-line-only treatment a docstring gets, because this is not one.
        assert measure_module(path).functions["f"] == 1 + span

    def test_a_model_of_ten_annotated_fields_measures_ten(self, tmp_path):
        fields = "\n".join(f"    field_{i}: int = {i}" for i in range(10))
        path = tmp_path / "model.py"
        path.write_text(f"class Model:\n{fields}\n")

        # own header (1) + 10 AnnAssign lines
        assert measure_module(path).classes["Model"] == 11

    def test_a_function_with_a_20_line_closure_measures_its_own_lines_plus_20(self, tmp_path):
        closure_lines = "\n".join(f"        y{i} = {i}" for i in range(20))
        source = f"def outer():\n    x = 1\n    def inner():\n{closure_lines}\n    return inner\n"
        path = tmp_path / "closure.py"
        path.write_text(source)

        measurement = measure_module(path)

        # own header (1) + x=1 (1) + def-inner header (1) + return (1) + the
        # closure's own 20 lines, folded directly in.
        assert measurement.functions["outer"] == 24
        assert "inner" not in measurement.functions
        assert "outer.inner" not in measurement.functions


