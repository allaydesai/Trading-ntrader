"""Size-cap ratchet: CLAUDE.md's <500/<100/<50 caps, enforced by AST (D4).

**Metric** (decided 2026-09-22, Epic 4 pre-work — see
``_bmad-output/implementation-artifacts/epic4-prework-spec.md``): the set of
distinct source lines occupied by ``ast.stmt`` nodes, excluding docstring
expressions. A compound statement (``if``/``for``/``while``/``with``/``try``/
``def``/``class``/``match``) contributes only its header line to whatever
scope it is directly nested in — its own body is measured separately and
rolled up into it. Concretely:

- A function's size is its own statements' lines, with a nested closure's
  lines folded directly in (ruling 3) — the closure gets **no key of its
  own**.
- A class's size is its own directly-owned statements' lines (field
  annotations, control flow) plus the sum of its methods' own sizes — each
  method **does** get its own key, ``Class.method``.
- A file's size is its own top-level statements' lines plus the sum of its
  classes' and top-level functions' sizes.

**Metric rulings** (same date, so the first person to hit one does not
relitigate it):

1. Field annotations count — a Pydantic/dataclass ``name: type = default``
   line is an ``AnnAssign`` statement like any other.
2. Multi-line literals count every line they occupy. A docstring is the only
   multi-line expression excluded, and only in docstring position (first
   statement of a module/class/function body).
3. Nested functions roll up into their parent and are not keyed separately;
   methods roll up into their class and *are* keyed; classes and functions
   both roll up into the file.

**Two caps, two enforcement shapes:**

- **File cap (hard)** — 500 lines, with a 3-entry allowlist carrying each
  listed file's recorded ceiling. A listed file may not exceed its ceiling;
  any other file may not exceed 500.
- **Class/function cap (ratchet)** — a ``SIZE_BASELINE`` mapping generated
  once from the tree's overages at D4's landing. The guard fails when (a) an
  unlisted class/function exceeds its cap, (b) a listed one exceeds its
  recorded value, or (c) a listed one now measures **at or under** its cap —
  stale entries must be removed, so the baseline only shrinks. Shrinking
  without dropping under the cap needs no edit (the entry is a ceiling, not
  an exact value).

Regenerate the baseline after a deliberate split with:
``python -m tests.unit.governance.test_size_caps --print-baseline``
"""

